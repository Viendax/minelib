#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_row_is_complete_and_parts_translate() {
        let mut seen = std::collections::HashSet::new();
        for r in TABLE {
            assert!(seen.insert(r[0]), "en double : {}", r[0]);
            assert!(r.iter().all(|t| !t.is_empty()), "{r:?}");
        }
        set("en");
        assert_eq!(translate("Jouer").as_deref(), Some("Play"));
        assert_eq!(
            translate("Plein écran : oui (F11)").as_deref(),
            Some("Fullscreen: yes (F11)")
        );
        assert_eq!(translate("texte inconnu"), None);
        // Éditeur de lumières : libellés, valeurs « Libellé : nombre », préréglages.
        assert_eq!(
            translate("Lumières automatiques : 3").as_deref(),
            Some("Automatic lights: 3")
        );
        assert_eq!(
            translate("F : caméra libre").as_deref(),
            Some("F: free camera")
        );
        for fr in crate::lights::QUALITY_NAMES
            .iter()
            .chain(&crate::lights::STYLE_NAMES)
            .chain(&minelib_render::SHADOW_QUALITY_NAMES)
            .filter(|n| **n != "Ultra")
        {
            assert!(translate(fr).is_some(), "{fr}");
        }
        set("fr");
        assert_eq!(translate("Jouer"), None);
        set("xx");
        assert_eq!(current(), 0);
    }
}
